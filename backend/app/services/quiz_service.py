import json
import logging
import re
from typing import Any

from app.services.ollama_service import (
    OllamaProcessingError,
    generate_response,
)

logger = logging.getLogger(__name__)

QUIZ_SYSTEM_PROMPT = """
You are an expert educational assessment AI assistant.
Your task is to generate high-quality multiple choice quizzes for students based on the provided learning material or academic topic.

CRITICAL INSTRUCTIONS:
- You MUST respond ONLY with valid JSON. Do not include markdown codeblocks or conversational text outside the JSON.
- Output MUST match this exact schema:
{
  "title": "Concise Quiz Title",
  "topic": "Subject / Topic Name",
  "questions": [
    {
      "question": "Clear and precise question text?",
      "options": [
        "A) Option 1",
        "B) Option 2",
        "C) Option 3",
        "D) Option 4"
      ],
      "correct_answer": "A) Option 1",
      "explanation": "Clear, educational explanation of why this answer is correct."
    }
  ]
}
- Ensure each question has exactly 4 options prefixed with A), B), C), D).
- The "correct_answer" MUST exactly match one of the items in the "options" list.
- Keep the difficulty aligned with the requested level (easy, medium, or hard).
- Do not make up facts; ground questions in the provided content.
"""


def clean_json_response(raw_text: str) -> dict[str, Any]:
    """
    Extract and parse JSON object from LLM output, handling possible markdown fences.
    """
    cleaned = raw_text.strip()
    if cleaned.startswith("```json"):
        cleaned = cleaned[7:]
    elif cleaned.startswith("```"):
        cleaned = cleaned[3:]
    if cleaned.endswith("```"):
        cleaned = cleaned[:-3]
    cleaned = cleaned.strip()

    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        # Fallback: search for first { and last }
        match = re.search(r"\{.*\}", cleaned, re.DOTALL)
        if match:
            return json.loads(match.group(0))
        raise OllamaProcessingError("Model did not return valid JSON for the quiz.")


def generate_quiz_content(
    content: str,
    topic: str | None = None,
    num_questions: int = 5,
    difficulty: str = "medium",
) -> dict[str, Any]:
    """
    Generate questions, options, answers, and explanations from text or topic.
    """
    effective_topic = topic or "General Concepts"
    truncated_content = content[:6000] if content else ""

    prompt = f"""
Generate an educational quiz with {num_questions} questions at {difficulty.upper()} difficulty level.

TOPIC: {effective_topic}

LEARNING MATERIAL / CONTEXT:
\"\"\"
{truncated_content if truncated_content else effective_topic}
\"\"\"

Requirements:
1. Generate exactly {num_questions} questions.
2. 4 choices per question (A, B, C, D).
3. Provide the correct answer and a brief conceptual explanation for every question.
4. Output strictly valid JSON matching the specified schema.
"""

    try:
        raw_response = generate_response(
            prompt=prompt,
            system_prompt=QUIZ_SYSTEM_PROMPT,
            as_json=True,
            timeout=180,
        )
        parsed = clean_json_response(raw_response)
    except Exception as exc:
        logger.warning("JSON quiz generation failed or timed out, trying text prompt fallback: %s", exc)
        # Fallback attempt without strict json constraint
        fallback_prompt = prompt + "\nRemember: respond with raw JSON only, no markdown."
        raw_response = generate_response(
            prompt=fallback_prompt,
            system_prompt=QUIZ_SYSTEM_PROMPT,
            as_json=False,
            timeout=180,
        )
        parsed = clean_json_response(raw_response)

    # Sanitize and validate questions list
    questions = parsed.get("questions", [])
    if not isinstance(questions, list) or len(questions) == 0:
        raise OllamaProcessingError("No questions were generated by the AI model.")

    sanitized_questions = []
    for q in questions[:num_questions]:
        q_text = q.get("question", "").strip()
        opts = q.get("options", [])
        if not isinstance(opts, list) or len(opts) < 2:
            continue
        corr = q.get("correct_answer", "").strip()
        expl = q.get("explanation", "").strip()

        # Ensure correct_answer is in options or find the best match
        if corr not in opts:
            matching = [opt for opt in opts if opt.lower().startswith(corr.lower()[:2])]
            if matching:
                corr = matching[0]
            else:
                corr = opts[0]

        sanitized_questions.append({
            "question": q_text,
            "options": opts,
            "correct_answer": corr,
            "explanation": expl or "Correct as per educational material.",
        })

    if not sanitized_questions:
        raise OllamaProcessingError("Failed to parse valid quiz questions from AI output.")

    return {
        "title": parsed.get("title", f"{effective_topic} Quiz"),
        "topic": parsed.get("topic", effective_topic),
        "difficulty": difficulty,
        "questions": sanitized_questions,
    }
